function nextMacroDrop(date) {
	const { day, h, m, s } = londonParts(date);
	const now = day * 86400 + h * 3600 + m * 60 + s;
	const cutoffs = [{
		at: 345600,
		drop: "Saturday"
	}, {
		at: 86400,
		drop: "Wednesday"
	}];
	let best = {
		left: Infinity,
		drop: ""
	};
	for (const c of cutoffs) {
		let left = c.at - now;
		if (left <= 0) left += 604800;
		if (left < best.left) best = {
			left,
			drop: c.drop
		};
	}
	return best;
}

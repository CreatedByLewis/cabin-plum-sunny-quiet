function londonParts(date) {
	const parts = new Intl.DateTimeFormat("en-GB", {
		timeZone: "Europe/London",
		weekday: "short",
		hour: "2-digit",
		minute: "2-digit",
		second: "2-digit",
		hourCycle: "h23"
	}).formatToParts(date);
	const get = (type) => parts.find((p) => p.type === type)?.value ?? "0";
	return {
		day: [
			"Sun",
			"Mon",
			"Tue",
			"Wed",
			"Thu",
			"Fri",
			"Sat"
		].indexOf(get("weekday")),
		h: +get("hour"),
		m: +get("minute"),
		s: +get("second")
	};
}
function secondsToFridayFive(date) {
	const { day, h, m, s } = londonParts(date);
	let diff = 493200 - (day * 86400 + h * 3600 + m * 60 + s);
	if (diff <= 0) diff += 604800;
	return diff;
}
